import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

// Keep the settings preview aligned with the TinyMCE version used by the client.
export async function generateToolbarIcons() {
  const source = new URL(
    "../client/node_modules/tinymce/icons/default/icons.js",
    import.meta.url,
  );
  const commands = {
    blocks: "paragraph",
    bold: "bold",
    italic: "italic",
    underline: "underline",
    strikethrough: "strike-through",
    forecolor: "text-color",
    backcolor: "highlight-bg-color",
    align: "align-left",
    numlist: "ordered-list",
    bullist: "unordered-list",
    link: "link",
    image: "image",
    table: "table",
    removeformat: "remove-formatting",
    code: "sourcecode",
    undo: "undo",
    redo: "redo",
    superscript: "superscript",
    subscript: "subscript",
    outdent: "outdent",
    indent: "indent",
    chevron: "chevron-down",
  };
  let icons;
  vm.runInNewContext(
    await readFile(source, "utf8"),
    {
      tinymce: {
        IconManager: {
          add: (_, pack) => {
            icons = pack.icons;
          },
        },
      },
    },
    { filename: fileURLToPath(source) },
  );
  const selected = Object.fromEntries(
    Object.entries(commands).map(([command, icon]) => {
      if (!icons?.[icon]) throw new Error(`Missing TinyMCE icon: ${icon}`);
      return [command, icons[icon]];
    }),
  );
  const target = new URL("src/lib/tinymce-toolbar-icons.ts", import.meta.url);
  const generated =
    "// Generated from TinyMCE default icons (GPL-2.0-or-later). Do not edit.\n// Regenerated by packages/scripts/generate-toolbar-icons.mjs during scripts builds.\nexport const toolbarIcons: Record<string, string> = " +
    JSON.stringify(selected, null, 2) +
    ";\n";
  const output = execFileSync(
    process.execPath,
    [
      fileURLToPath(
        new URL("../../node_modules/@biomejs/biome/bin/biome", import.meta.url),
      ),
      "format",
      "--stdin-file-path",
      fileURLToPath(target),
    ],
    { input: generated, encoding: "utf8" },
  );
  let previous;
  try {
    previous = await readFile(target, "utf8");
  } catch {}
  if (previous !== output) await writeFile(target, output);
}
